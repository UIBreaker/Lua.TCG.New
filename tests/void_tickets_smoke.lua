local T=require("src.void_tickets")
local Game=require("src.game_state")
local Run=require("src.run_manager")
local P=require("src.persistence")
local Loadout=require("src.loadout")
local G=require("src.void_gacha")
local Shop=require("src.shop")
local function game()
    local g=Game.new();g.run=Run.newRun("red_deck");g.gold=40;return g
end
local g=game();g.voidTickets=667
assert(T.count(g)==667 and #g.backpackConsumables==667 and #g.consumables==0)
assert(T.count(g)==667,"legacy migration only once")
local stacks=Loadout.consumableStacks(g);assert(#stacks==7 and stacks[1].count==99 and stacks[7].count==73)
g=P.restoreSnapshot(P.makeSnapshot(g,"shop"));assert(T.count(g)==667 and #g.backpackConsumables==667)
assert(Loadout.move(g,"consumable","reserve",1,2,false));assert(T.count(g)==667 and #g.consumables==1)
assert(T.redeem(g,"reserve",1,99) and T.count(g)==568 and g.gold==139)
assert(require("src.inventory").useUtility(g,1) and T.count(g)==567 and g.gold==140 and #g.consumables==0)
local before=P.encode(P.makeSnapshot(g,"shop"))
assert(not T.spend(g,568) and not T.spend(g,-1) and not T.redeem(g,"forged",1,1) and not T.redeem(g,"reserve",1,1000))
assert(P.encode(P.makeSnapshot(g,"shop"))==before)
assert(T.spend(g,567) and T.count(g)==0 and #g.backpackConsumables==0)
assert(T.add(g,12));g.voidEvent={freeRemaining=0,goldMultiplier=1,results={},serial=0,totalRolls=0}
assert(G.quote(g,1,"ticket").cost==10 and G.quote(g,10,"ticket").cost==100)
assert(not G.quote(g,10,"ticket").affordable and G.quote(g,1,"ticket").affordable)
assert(T.spend(g,10) and T.count(g)==2)
assert(Shop.sellStoredItem(g,"reserve_consumable",1));assert(g.gold==141 and T.count(g)==1)
assert(T.add(g,98));stacks=Loadout.consumableStacks(g);assert(stacks[1].count==99)
g=P.restoreSnapshot(P.makeSnapshot(g,"void"));assert(T.count(g)==99)
Game.resetRun(g,"red_deck");assert(T.count(g)==0 and #g.backpackConsumables==0)
print("Void tickets PASS: old 667 wallet migration/no duplicates, 99 stacks, slots, 1:1 single/bulk redemption/sale, atomic invalid spend, 10/100 quotes, physical deduction, save and reset")
