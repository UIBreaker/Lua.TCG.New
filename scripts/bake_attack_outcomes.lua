-- Run with python scripts/verify_audio_runtime.py --bake-outcomes.
-- Reuse the actual game synthesizer; no third-party samples or gameplay RNG.
local function le(value,bytes)
    local parts={}
    for i=1,bytes do parts[i]=string.char(value%256);value=math.floor(value/256) end
    return table.concat(parts)
end
local entries,bytes={},0
local function bake(folder,name,data,cue)
    local path="assets/audio/"..folder.."/"..name..".wav"
    local pcm=data:getString()
    local wav="RIFF"..le(36+#pcm,4).."WAVEfmt "..le(16,4)..le(1,2)..le(2,2)..le(32000,4)
        ..le(128000,4)..le(4,2)..le(16,2).."data"..le(#pcm,4)..pcm
    local previous=io.open(path,"rb");local old=previous and previous:read('*a');if previous then previous:close() end
    if old~=wav then local file=assert(io.open(path,"wb"));file:write(wav);file:close() end
    bytes=bytes+#wav
    local fields={"path="..string.format("%q",path)}
    local keys={};for key in pairs(cue) do if key~="path" then keys[#keys+1]=key end end;table.sort(keys)
    for _,key in ipairs(keys) do fields[#fields+1]=key.."="..string.format("%.17g",cue[key]) end
    entries[#entries+1]="    ["..string.format("%q",name).."]={"..table.concat(fields,",").."},\n"
end
require("src.nen_audio").register({registerProcedural=function(name,data,cue) bake("nen_outcomes",name,data,cue) end},true)
assert(#entries==#require("config.nen_vfx_config").order*25,"all attack phases must be baked")
table.sort(entries)
local catalog=assert(io.open("config/attack_outcome_audio.lua","wb"))
catalog:write("-- Generated by scripts/bake_attack_outcomes.lua; rebuild after editing attack scores or synthesis.\nreturn {\n"..table.concat(entries).."}\n")
catalog:close()
print(string.format("Baked %d attack WAVs, %.1f MiB, with exact mixer metadata",#entries,bytes/1048576))
entries,bytes={},0
require("src.reward_audio").register({registerProcedural=function(name,data,cue) bake("reward_cues",name,data,cue) end})
assert(#entries==40,"all reward phases must be baked")
table.sort(entries)
local reward=assert(io.open("config/reward_audio_baked.lua","wb"))
reward:write("-- Generated by scripts/bake_attack_outcomes.lua.\nreturn {\n"..table.concat(entries).."}\n");reward:close()
print(string.format("Baked %d reward WAVs, %.1f MiB",#entries,bytes/1048576))
